// Constexpr Gaussian blur coefficients (float literals only for nvcc).
//
// Standard (gaussian_tail_width::standard): sigma = R = RadiusTenths/10, taps by band:
//  - 9 rows x 3-FIR (R=1..9)
//  - 11 rows x 5-FIR (R=10..20)
//  - 10 rows x 7/9/11/13/15/17/19/21-FIR (R=21..100 by band)
//
// Wide (gaussian_tail_width::wide): same sigma = R, taps = 2*taps_std - 1 (support ~2*sigma):
//  - 9 rows x 5-FIR (R=1..9)
//  - 11 rows x 9-FIR (R=10..20)
//  - 10 rows x 13-FIR (R=21..30)
//  - 10 rows x 17-FIR (R=31..40)
//  - 10 rows x 21-FIR (R=41..50)
// Wide requires RadiusTenths <= 50 (enforced by GaussianBlur static_assert).
